$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

if (-not (Test-Path './docker-compose.yml')) {
    throw 'Place these files in the project root beside docker-compose.yml.'
}
if (-not (Test-Path './.env')) {
    throw 'Missing .env. Copy .env.example to .env first.'
}

# Read the FINAL value that Docker Compose passes to Java, rather than manually
# parsing .env. This correctly handles blank strings, quotes, and comments.
$dockerExe = Get-Command 'docker.exe' -ErrorAction SilentlyContinue
if (-not $dockerExe) {
    throw 'Docker CLI was not found. Open Docker Desktop and ensure docker.exe is in PATH.'
}
$composeOutput = & $dockerExe.Source compose -f 'docker-compose.yml' config --format json
if ($LASTEXITCODE -ne 0) {
    throw 'Docker Compose config failed. Check .env and docker-compose.yml.'
}
try {
    $resolvedCompose = ($composeOutput -join "`n") | ConvertFrom-Json -ErrorAction Stop
} catch {
    throw 'Cannot read Docker Compose configuration as JSON. Update Docker Compose v2 and retry.'
}
$adminHash = [string]$resolvedCompose.services.server.environment.ADMIN_PASSWORD_HASH
$adminHash = $adminHash.Trim()
if ([string]::IsNullOrWhiteSpace($adminHash)) {
    Write-Warning 'ADMIN_PASSWORD_HASH is empty: Admin login uses admin / admin123.'
    Write-Warning 'Funnel exposes the site PUBLICLY; change Admin and branch passwords before sharing any links.'
} elseif ($adminHash -notmatch '^[0-9a-fA-F]{64}$') {
    # Never print a password/hash to logs.
    Write-Host ('[ERROR] Docker Compose reads ADMIN_PASSWORD_HASH as NON-EMPTY (' + $adminHash.Length + ' chars), but it is not a 64-character SHA-256 hex hash.') -ForegroundColor Red
    Write-Host '[FIX] To use the default login admin/admin123, open .env and use the EXACT line:' -ForegroundColor Yellow
    Write-Host '      ADMIN_PASSWORD_HASH='
    Write-Host '[FIX] Alternatively, replace it with your valid 64-character SHA-256 hex hash.' -ForegroundColor Yellow
    throw 'Invalid ADMIN_PASSWORD_HASH in .env. Fix the line above, then rerun run_public_web.bat.'
} else {
    Write-Host '[OK] Custom ADMIN_PASSWORD_HASH is configured.'
}

$tailscale = Get-Command 'tailscale.exe' -ErrorAction SilentlyContinue
if ($tailscale) {
    $tailscaleBin = $tailscale.Source
} else {
    $tailscaleBin = Join-Path $env:ProgramFiles 'Tailscale\tailscale.exe'
    if (-not (Test-Path $tailscaleBin)) { throw 'Tailscale is not installed or not in PATH.' }
}

$json = (& $tailscaleBin status --json) -join "`n"
if ($LASTEXITCODE -ne 0) { throw 'Cannot read Tailscale status. Please log in first.' }
$status = $json | ConvertFrom-Json
$dns = [string]$status.Self.DNSName
$dns = $dns.TrimEnd('.')
if (-not $dns.EndsWith('.ts.net')) {
    throw 'Tailscale MagicDNS name is unavailable. Enable MagicDNS and HTTPS in Tailscale.'
}

$template = @"
# Automatically generated by prepare_tunnel.ps1. Do not commit secrets to Git.
services:
  server:
    command:
      - server
      - security.allowed.origins=https://$dns
      - experiment.api=false
    environment:
      JAVA_OPTS: "-Xmx256m -Djava.awt.headless=true"
  cn01:
    command:
      - client
      - http.port=8081
      - security.allowed.origins=https://$($dns):8443
    environment:
      JAVA_OPTS: "-Xmx256m -Djava.awt.headless=true"
  cn02:
    command:
      - client
      - http.port=8082
      - security.allowed.origins=https://$($dns):10000
    environment:
      JAVA_OPTS: "-Xmx256m -Djava.awt.headless=true"
"@
[System.IO.File]::WriteAllText((Join-Path $PSScriptRoot 'docker-compose.tunnel.yml'), $template, (New-Object System.Text.UTF8Encoding $false))
Write-Host ''
Write-Host 'Tailscale HTTPS host:' $dns
Write-Host "Admin: https://$dns/admin/"
Write-Host "CN01 : https://$($dns):8443/branch/"
Write-Host "CN02 : https://$($dns):10000/branch/"
Write-Host 'TCP  : use Tailscale IP on port 5000 (private tailnet only)'
Write-Host ''
